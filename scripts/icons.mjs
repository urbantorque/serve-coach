#!/usr/bin/env node
/**
 * The app's icons, as two small files: `node scripts/icons.mjs`.
 *
 * Every glyph comes from Phosphor (MIT), at one weight, so the set agrees with
 * itself. The package's React components carry six weights per icon, which on
 * the entry chunk's budget would cost more than the whole home screen, so only
 * the path of each glyph in use is lifted out into `src/components/icons.ts`.
 *
 * The package is nine thousand small files for thirty glyphs, so it is not a
 * dependency. To add an icon: `npm pack @phosphor-icons/core`, unpack it
 * anywhere, add the glyph below, and run this with `PHOSPHOR=<that folder>`.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = process.cwd()
const dir = join(process.env.PHOSPHOR ?? '', 'assets')

/** The app's name for each glyph, and which Phosphor glyph it is. */
const GLYPHS = {
  back: 'caret-left',
  camera: 'video-camera',
  'camera-solid': 'video-camera-fill',
  calendar: 'calendar-blank',
  check: 'check',
  chevron: 'caret-right',
  clock: 'clock',
  close: 'x',
  film: 'film-strip',
  flag: 'flag-checkered',
  gallery: 'images',
  gauge: 'gauge',
  home: 'sun-horizon',
  info: 'info',
  lightning: 'lightning',
  offline: 'download-simple',
  pause: 'pause-fill',
  play: 'play-fill',
  progress: 'chart-line-up',
  repeat: 'arrows-clockwise',
  settings: 'gear-six',
  share: 'export',
  shield: 'shield-check',
  sound: 'speaker-high',
  target: 'target',
  trash: 'trash',
  trophy: 'trophy',
  up: 'arrow-up-right',
  upload: 'upload-simple',
  warn: 'warning',
}

const pathOf = (glyph) => {
  const weight = glyph.endsWith('-fill') ? 'fill' : 'bold'
  const name = glyph.endsWith('-fill') ? `${glyph}.svg` : `${glyph}-bold.svg`
  const svg = readFileSync(join(dir, weight, name), 'utf8')
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1])
  if (!paths.length) throw new Error(`no path in ${name}`)
  return paths.join(' ')
}

/**
 * The glyphs only the screens behind the first one draw (E0.3). They go to
 * `iconsMore.ts`, which loads after the first paint; everything else stays on
 * the entry chunk. `iconSplit.test.ts` fails if an entry module draws one of
 * these, and names the first-screen glyphs no entry module draws.
 */
const LATER = ['back', 'calendar', 'chevron', 'clock', 'gallery', 'pause', 'play', 'repeat', 'share', 'sound', 'target', 'trash', 'warn']

const line = ([name, glyph]) => `  ${/-/.test(name) ? `'${name}'` : name}: '${pathOf(glyph)}',`
const first = Object.entries(GLYPHS).filter(([name]) => !LATER.includes(name)).map(line)
const later = Object.entries(GLYPHS).filter(([name]) => LATER.includes(name)).map(line)

writeFileSync(
  join(root, 'src', 'components', 'icons.ts'),
  `/**
 * Generated by \`scripts/icons.mjs\`: Phosphor Icons (MIT), bold weight, on a
 * 256-unit grid. Add a glyph there, not here.
 *
 * The glyphs the first screen draws. Every other glyph is in \`iconsMore.ts\`,
 * which loads after the first screen has painted (E0.3).
 */
import type { MORE_GLYPHS } from './iconsMore'

export const GLYPHS = {
${first.join('\n')}
} as const

export type IconName = keyof typeof GLYPHS | keyof typeof MORE_GLYPHS
`,
)
writeFileSync(
  join(root, 'src', 'components', 'iconsMore.ts'),
  `/**
 * Generated by \`scripts/icons.mjs\`: Phosphor Icons (MIT), bold weight, on a
 * 256-unit grid. Add a glyph there, not here.
 *
 * The glyphs only the screens behind the first one draw, off the entry chunk
 * (E0.3): \`Icon\` fetches this file after the first paint.
 */
export const MORE_GLYPHS = {
${later.join('\n')}
} as const
`,
)
console.log(`${first.length} glyphs first, ${later.length} later`)
